  /// <summary>Next bit-history state after <paramref name="bit"/>.</summary>
  public static int Next(int state, int bit) => States[state * 4 + bit];

  /// <summary>Zero count of a state.</summary>
  public static int Zeros(int state) => States[state * 4 + 2];

  /// <summary>One count of a state.</summary>
  public static int Ones(int state) => States[state * 4 + 3];

  /// <summary>1/(1+e^-d): d scaled by 8 bits (±2047), result 12 bits.</summary>
  public static int Squash(int d) {
    if (d > 2047) return 4095;
    if (d < -2047) return 0;
    var w = d & 127;
    var k = (d >> 7) + 16;
    return (SquashPoints[k] * (128 - w) + SquashPoints[k + 1] * w + 64) >> 7;
  }

  /// <summary>ilog over 32 bits.</summary>
  public static int LongLog(uint x) =>
    x >= 0x1000000 ? 256 + Log[x >> 16] : x >= 0x10000 ? 128 + Log[x >> 8] : Log[x];

  /// <summary>The model's 2–5 argument context hash.</summary>
  public static uint Hash(uint a, uint b, uint c = 0xFFFFFFFF, uint d = 0xFFFFFFFF, uint e = 0xFFFFFFFF) {
    var h = unchecked(a * 200002979u + b * 30005491u + c * 50004239u + d * 70004807u + e * 110002499u);
    return h ^ h >> 9 ^ a >> 2 ^ b >> 3 ^ c >> 4 ^ d >> 5 ^ e >> 6;
  }

  private static short[] BuildStretch() {
    var t = new short[4096];
    var next = 0;
    for (var x = -2047; x <= 2047; ++x) {
      var top = Squash(x);
      for (var j = next; j <= top; ++j) t[j] = (short)x;
      next = top + 1;
    }
    t[4095] = 2047;
    return t;
  }

  private static byte[] BuildLog() {
    var t = new byte[65536];
    var acc = 14155776u;
    for (var i = 2; i < 65536; ++i) {
      acc = unchecked(acc + 774541002u / (uint)(i * 2 - 1));
      t[i] = (byte)(acc >> 24);
    }
    return t;
  }
