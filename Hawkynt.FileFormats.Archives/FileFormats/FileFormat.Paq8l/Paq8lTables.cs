/// <summary>The model's shared lagged-Fibonacci generator (docs/PAQ8L-FORMAT.md §4.4).</summary>
internal sealed class Paq8lRandom {
  private readonly uint[] _table = new uint[64];
  private int _index;

  public Paq8lRandom() {
    this._table[0] = 123456789;
    this._table[1] = 987654321;
    for (var j = 0; j < 62; ++j)
      this._table[j + 2] = unchecked(this._table[j + 1] * 11 + this._table[j] * 23 / 16);
  }

  public uint Next() {
    ++this._index;
    return this._table[this._index & 63] = this._table[(this._index - 24) & 63] ^ this._table[(this._index - 55) & 63];
  }
}
