  /// <summary>A 258-entry table from its leading values (the rest zero).</summary>
  private static byte[] Table(params byte[] leading) {
    var table = new byte[258];
    leading.CopyTo(table, 0);
    return table;
  }

  /// <summary>The sparse table: weight 0x0A for byte 0, the given weight at one more index.</summary>
  private static byte[] Table(byte first, (int Index, byte Weight) other) {
    var table = new byte[258];
    table[0] = first;
    table[other.Index] = other.Weight;
    return table;
  }

  /// <summary>A stereo table: values at 0x00, 0x40 and 0x80, the rest zero.</summary>
  private static byte[] Stereo(byte[] at0, byte[] at40, byte[] at80) {
    var table = new byte[258];
    at0.CopyTo(table, 0x00);
    at40.CopyTo(table, 0x40);
    at80.CopyTo(table, 0x80);
    return table;
  }
