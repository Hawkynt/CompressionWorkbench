namespace FileFormat.Mpq;

/// <summary>
/// MPQ compression method 0x01: Blizzard's adaptive Huffman coding (FGK-style), used after ADPCM
/// on WAVE sectors. The first byte selects one of nine initial weight tables; the tree then grows
/// with every new symbol (escape 0x101 followed by the raw byte) and ends at symbol 0x100.
/// </summary>
/// <remarks>
/// Converted from StormLib <c>src/huffman/huff.cpp</c> (Ladislav Zezula, ShadowFlare; MIT) — see
/// <c>THIRD-PARTY-NOTICE.StormLib.txt</c>. The weight tables are copied exactly. The quick-link
/// cache of the original is a decoding shortcut with no effect on the output and is left out.
/// Two behaviours are kept exactly because the stream depends on them: weights only grow for
/// data type 0 (and on the insertion of a new symbol), and the tree is a single weight-ordered
/// list whose order decides which child is the "0" branch.
/// </remarks>
internal static class MpqHuffman {

  private const int EndOfStream = 0x100;
  private const int NewSymbol = 0x101;
  private const int MaxItems = 515;

  /// <summary>Decodes a stream into at most <paramref name="maxOutput"/> bytes.</summary>
  /// <exception cref="InvalidDataException">The stream is malformed or truncated.</exception>
  internal static byte[] Decompress(ReadOnlySpan<byte> input, int maxOutput) {
    if (maxOutput <= 0)
      return [];
    var bits = new BitInput(input);
    if (!bits.TryRead8(out var dataType))
      throw new InvalidDataException("MPQ Huffman stream has no data-type byte.");

    var tree = new Tree((int)dataType);
    var output = new List<byte>(maxOutput);
    while (true) {
      var value = tree.Decode(ref bits);
      if (value == EndOfStream)
        break;
      if (value == NewSymbol) {
        if (!bits.TryRead8(out var raw))
          throw new InvalidDataException("MPQ Huffman stream ends inside a new symbol.");
        value = (int)raw;
        tree.InsertNewBranch(tree.LastItem.Value, value);
        if (!tree.IsSparse)
          tree.IncrementWeights(tree.ByValue[value]!);
      }

      if (output.Count >= maxOutput)
        break;
      output.Add((byte)value);
      if (tree.IsSparse)
        tree.IncrementWeights(tree.ByValue[value]!);
    }
    return [.. output];
  }

  /// <summary>Encodes <paramref name="input"/> with the initial weights of <paramref name="dataType"/>.</summary>
  internal static byte[] Compress(ReadOnlySpan<byte> input, int dataType) {
    var tree = new Tree(dataType);
    var output = new BitOutput(input.Length + 16);
    output.Put((uint)dataType, 8);

    foreach (var symbol in input) {
      var item = tree.ByValue[symbol];
      if (item == null) {
        tree.Encode(ref output, tree.ByValue[NewSymbol]!);
        output.Put(symbol, 8);
        tree.InsertNewBranch(tree.LastItem.Value, symbol);
        tree.IncrementWeights(tree.ByValue[symbol]!);
        continue;
      }
      tree.Encode(ref output, item);
      if (tree.IsSparse)
        tree.IncrementWeights(item);
    }

    tree.Encode(ref output, tree.ByValue[EndOfStream]!);
    return output.ToArray();
  }

  private sealed class Item {
    public Item? Next;      // towards lower weight
    public Item? Previous;  // towards higher weight
    public int Value;
    public uint Weight;
    public Item? Parent;
    public Item? ChildLow;  // the higher-weight child is ChildLow.Previous

    public void Unlink() {
      if (this.Next == null)
        return;
      this.Previous!.Next = this.Next;
      this.Next.Previous = this.Previous;
      this.Next = this.Previous = null;
    }
  }

  private sealed class Tree {
    // List head sentinel: Head.Next = highest weight, Head.Previous = lowest weight.
    private readonly Item _head = new();
    private int _itemsUsed;

    public readonly Item?[] ByValue = new Item?[258];
    public readonly bool IsSparse;

    public Item LastItem => this._head.Previous!;

    public Tree(int dataType) {
      this._head.Next = this._head.Previous = this._head;
      this.IsSparse = dataType == 0;
      var index = dataType & 0x0F;
      if (index >= Distributions.Length)
        throw new InvalidDataException($"MPQ Huffman data type {dataType} has no weight table.");
      this.Build(Distributions[index]);
    }

    private static void LinkAfter(Item anchor, Item item) {
      item.Next = anchor.Next;
      item.Previous = anchor.Next!.Previous;
      anchor.Next!.Previous = item;
      anchor.Next = item;
    }

    private Item FindHigherOrEqual(Item? start, uint weight) {
      if (start != null)
        for (var item = start; item != this._head; item = item.Previous!)
          if (item.Weight >= weight)
            return item;
      return this._head;
    }

    private Item Create(int value, uint weight, bool insertAfterHead) {
      if (this._itemsUsed >= MaxItems)
        throw new InvalidDataException("MPQ Huffman tree overflowed its item pool.");
      ++this._itemsUsed;
      var item = new Item { Value = value, Weight = weight };
      LinkAfter(insertAfterHead ? this._head : this._head.Previous!, item);
      return item;
    }

    private uint FixPosition(Item item, uint maxWeight) {
      if (item.Weight < maxWeight) {
        var higher = this.FindHigherOrEqual(this._head.Previous, item.Weight);
        item.Unlink();
        LinkAfter(higher, item);
        return maxWeight;
      }
      return item.Weight;
    }

    private void Build(byte[] weights) {
      uint maxWeight = 0;
      for (var i = 0; i < 0x100; ++i) {
        if (weights[i] == 0)
          continue;
        var item = this.Create(i, weights[i], insertAfterHead: true);
        this.ByValue[i] = item;
        maxWeight = this.FixPosition(item, maxWeight);
      }

      this.ByValue[EndOfStream] = this.Create(EndOfStream, 1, insertAfterHead: false);
      this.ByValue[NewSymbol] = this.Create(NewSymbol, 1, insertAfterHead: false);

      var low = this._head.Previous!;
      while (low != this._head) {
        var high = low.Previous!;
        if (high == this._head)
          break;
        var parent = this.Create(0, high.Weight + low.Weight, insertAfterHead: true);
        low.Parent = parent;
        high.Parent = parent;
        parent.ChildLow = low;
        maxWeight = this.FixPosition(parent, maxWeight);
        low = high.Previous!;
      }
    }

    public void IncrementWeights(Item? item) {
      for (; item != null; item = item.Parent) {
        ++item.Weight;
        var higher = this.FindHigherOrEqual(item.Previous, item.Weight);
        var swap = higher.Next!;
        if (swap == item)
          continue;

        swap.Unlink();
        LinkAfter(item, swap);
        item.Unlink();
        LinkAfter(higher, item);

        var swapSiblingLow = swap.Parent!.ChildLow;
        var parent = item.Parent!;
        if (parent.ChildLow == item)
          parent.ChildLow = swap;
        if (swapSiblingLow == swap)
          swap.Parent.ChildLow = item;
        parent = item.Parent!;
        item.Parent = swap.Parent;
        swap.Parent = parent;
      }
    }

    public void InsertNewBranch(int value1, int value2) {
      var last = this._head.Previous!;
      var high = this.Create(value1, last.Weight, insertAfterHead: false);
      high.Parent = last;
      this.ByValue[value1] = high;

      var low = this.Create(value2, 0, insertAfterHead: false);
      low.Parent = last;
      last.ChildLow = low;
      this.ByValue[value2] = low;

      this.IncrementWeights(low);
    }

    public void Encode(ref BitOutput output, Item item) {
      uint buffer = 0;
      var count = 0;
      for (var parent = item.Parent; parent != null; item = parent, parent = parent.Parent) {
        buffer = (buffer << 1) | (parent.ChildLow != item ? 1u : 0u);
        ++count;
      }
      output.Put(buffer, count);
    }

    public int Decode(ref BitInput bits) {
      var item = this._head.Next;
      if (item == this._head)
        throw new InvalidDataException("MPQ Huffman tree is empty.");
      while (item!.ChildLow != null) {
        if (!bits.TryRead1(out var bit))
          throw new InvalidDataException("MPQ Huffman stream ends before its end marker.");
        item = bit != 0 ? item.ChildLow.Previous : item.ChildLow;
      }
      return item.Value;
    }
  }

  private ref struct BitInput(ReadOnlySpan<byte> data) {
    private readonly ReadOnlySpan<byte> _data = data;
    private int _position;
    private uint _buffer;
    private int _count;

    public bool TryRead1(out uint bit) {
      if (this._count == 0) {
        if (this._position >= this._data.Length) {
          bit = 0;
          return false;
        }
        this._buffer = this._data[this._position++];
        this._count = 8;
      }
      bit = this._buffer & 1;
      this._buffer >>= 1;
      --this._count;
      return true;
    }

    public bool TryRead8(out uint value) {
      if (this._count < 8) {
        if (this._position >= this._data.Length) {
          value = 0;
          return false;
        }
        this._buffer |= (uint)this._data[this._position++] << this._count;
        this._count += 8;
      }
      value = this._buffer & 0xFF;
      this._buffer >>= 8;
      this._count -= 8;
      return true;
    }
  }

  private struct BitOutput(int capacity) {
    private readonly List<byte> _bytes = new(capacity);
    private ulong _buffer;
    private int _count;

    public void Put(uint value, int count) {
      this._buffer |= (ulong)value << this._count;
      this._count += count;
      while (this._count >= 8) {
        this._bytes.Add((byte)this._buffer);
        this._buffer >>= 8;
        this._count -= 8;
      }
    }

    public readonly byte[] ToArray() {
      var result = new byte[this._bytes.Count + (this._count > 0 ? 1 : 0)];
      this._bytes.CopyTo(result);
      if (this._count > 0)
        result[^1] = (byte)this._buffer;
      return result;
    }
  }

