  private const int MdsPolynomial = 0x169, RsPolynomial = 0x14D;

  private readonly uint[] _subkeys = new uint[8 + 2 * Rounds];
  private readonly uint[][] _sbox = [new uint[256], new uint[256], new uint[256], new uint[256]];

  /// <summary>Expands a 16-, 24- or 32-byte <paramref name="key"/>.</summary>
  /// <exception cref="ArgumentException">The key is not 16, 24 or 32 bytes long.</exception>
  public Twofish(ReadOnlySpan<byte> key) {
    if (key.Length is not (16 or 24 or 32))
      throw new ArgumentException("Twofish keys are 16, 24 or 32 bytes.", nameof(key));
    var k = key.Length / 8;
    var even = new uint[k];
    var odd = new uint[k];
    var sboxKey = new uint[k];
    for (var i = 0; i < k; ++i) {
      even[i] = BinaryPrimitives.ReadUInt32LittleEndian(key[(8 * i)..]);
      odd[i] = BinaryPrimitives.ReadUInt32LittleEndian(key[(8 * i + 4)..]);
      sboxKey[k - 1 - i] = ReedSolomon(key.Slice(8 * i, 8));
    }

    for (var i = 0; i < this._subkeys.Length / 2; ++i) {
      var a = H((uint)(2 * i) * Rho, even);
      var b = uint.RotateLeft(H((uint)(2 * i + 1) * Rho, odd), 8);
      this._subkeys[2 * i] = a + b;
      this._subkeys[2 * i + 1] = uint.RotateLeft(a + 2 * b, 9);
    }

    // g(X) = h(X, S) splits into four byte lookups whose MDS columns are XORed together.
    for (var x = 0; x < 256; ++x)
      for (var column = 0; column < 4; ++column) {
        var y = KeyedPermutation((byte)x, column, sboxKey);
        uint word = 0;
        for (var row = 0; row < 4; ++row)
          word |= (uint)Multiply(Mds[row, column], y, MdsPolynomial) << (8 * row);
        this._sbox[column][x] = word;
      }
  }

  /// <summary>Encrypts one 16-byte block in place.</summary>
  public void Encrypt(Span<byte> block) {
    if (block.Length != 16)
      throw new ArgumentException("Twofish blocks are 16 bytes.", nameof(block));
    var key = this._subkeys;
    var r0 = BinaryPrimitives.ReadUInt32LittleEndian(block) ^ key[0];
    var r1 = BinaryPrimitives.ReadUInt32LittleEndian(block[4..]) ^ key[1];
    var r2 = BinaryPrimitives.ReadUInt32LittleEndian(block[8..]) ^ key[2];
    var r3 = BinaryPrimitives.ReadUInt32LittleEndian(block[12..]) ^ key[3];
    for (var round = 0; round < Rounds; ++round) {
      var t0 = this.G(r0);
      var t1 = this.G(uint.RotateLeft(r1, 8));
      var f0 = t0 + t1 + key[2 * round + 8];
      var f1 = t0 + 2 * t1 + key[2 * round + 9];
      var n2 = uint.RotateRight(r2 ^ f0, 1);
      var n3 = uint.RotateLeft(r3, 1) ^ f1;
      (r0, r1, r2, r3) = (n2, n3, r0, r1);
    }
    BinaryPrimitives.WriteUInt32LittleEndian(block, r2 ^ key[4]);
    BinaryPrimitives.WriteUInt32LittleEndian(block[4..], r3 ^ key[5]);
    BinaryPrimitives.WriteUInt32LittleEndian(block[8..], r0 ^ key[6]);
    BinaryPrimitives.WriteUInt32LittleEndian(block[12..], r1 ^ key[7]);
  }

  private uint G(uint x)
    => this._sbox[0][(byte)x] ^ this._sbox[1][(byte)(x >> 8)] ^ this._sbox[2][(byte)(x >> 16)] ^ this._sbox[3][x >> 24];

  /// <summary>The function h of the paper: the keyed permutations of each byte, then the MDS matrix.</summary>
  private static uint H(uint x, uint[] list) {
    uint result = 0;
    for (var column = 0; column < 4; ++column) {
      var y = KeyedPermutation((byte)(x >> (8 * column)), column, list);
      for (var row = 0; row < 4; ++row)
        result ^= (uint)Multiply(Mds[row, column], y, MdsPolynomial) << (8 * row);
    }
    return result;
  }

  /// <summary>Byte <paramref name="column"/> of h before the MDS matrix: the q0/q1 chain keyed with the bytes of <paramref name="list"/>.</summary>
  private static byte KeyedPermutation(byte y, int column, uint[] list) {
    byte L(int i) => (byte)(list[i] >> (8 * column));
    var k = list.Length;
    if (k == 4)
      y = (byte)((column is 0 or 3 ? Q1[y] : Q0[y]) ^ L(3));
    if (k >= 3)
      y = (byte)((column is 0 or 1 ? Q1[y] : Q0[y]) ^ L(2));
    return column switch {
      0 => Q1[Q0[Q0[y] ^ L(1)] ^ L(0)],
      1 => Q0[Q0[Q1[y] ^ L(1)] ^ L(0)],
      2 => Q1[Q1[Q0[y] ^ L(1)] ^ L(0)],
      _ => Q0[Q1[Q1[y] ^ L(1)] ^ L(0)],
    };
  }

  /// <summary>One word of the S-box key: the RS matrix times eight key bytes.</summary>
  private static uint ReedSolomon(ReadOnlySpan<byte> m) {
    uint word = 0;
    for (var row = 0; row < 4; ++row) {
      byte acc = 0;
      for (var j = 0; j < 8; ++j)
        acc ^= Multiply(Rs[row, j], m[j], RsPolynomial);
      word |= (uint)acc << (8 * row);
    }
    return word;
  }

  /// <summary>Multiplication in GF(2^8) modulo <paramref name="polynomial"/>.</summary>
  private static byte Multiply(byte a, byte b, int polynomial) {
    int x = a, y = b, product = 0;
    while (y != 0) {
      if ((y & 1) != 0)
        product ^= x;
      x <<= 1;
      if ((x & 0x100) != 0)
        x ^= polynomial;
      y >>= 1;
    }
    return (byte)product;
  }
