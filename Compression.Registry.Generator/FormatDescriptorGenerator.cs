using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;

namespace Compression.Registry.Generator;

/// <summary>
/// Roslyn incremental source generator that discovers all public non-abstract types implementing
/// IFormatDescriptor, IBuildingBlock and IFilesystemDriverAdapter across referenced assemblies and generates:
/// 1. A partial FormatRegistration class with explicit constructor calls (zero reflection)
/// 2. A Format enum inside FormatDetector with all discovered format IDs plus special values
///
/// Descriptors declared under a FileSystem.* namespace are explicitly marked as
/// filesystems when registered. FormatRegistry can therefore enforce that every
/// filesystem has a common-driver path without guessing from extensions/names.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class FormatDescriptorGenerator : IIncrementalGenerator {

  private const string DescriptorInterfaceFullName = "Compression.Registry.IFormatDescriptor";
  private const string BuildingBlockInterfaceFullName = "Compression.Registry.IBuildingBlock";
  private const string FilesystemDriverAdapterInterfaceFullName = "Compression.Registry.IFilesystemDriverAdapter";

  private static readonly string[] SpecialFormats = [
    "Unknown", "Sfx", "Iso", "Udf",
    "TarGz", "TarBz2", "TarXz", "TarZst", "TarLz4", "TarLzip", "TarBr",
  ];

  public void Initialize(IncrementalGeneratorInitializationContext context) {
    var allTypes = context.CompilationProvider.Select((compilation, ct) => {
      var descriptorInterface = compilation.GetTypeByMetadataName(DescriptorInterfaceFullName);
      var buildingBlockInterface = compilation.GetTypeByMetadataName(BuildingBlockInterfaceFullName);
      var filesystemDriverAdapterInterface = compilation.GetTypeByMetadataName(FilesystemDriverAdapterInterfaceFullName);

      var descriptors = new List<(string FullName, string Id, bool IsFilesystem)>();
      var buildingBlocks = new List<string>();
      var filesystemDrivers = new List<string>();

      if (descriptorInterface != null || buildingBlockInterface != null || filesystemDriverAdapterInterface != null) {
        foreach (var reference in compilation.References) {
          if (compilation.GetAssemblyOrModuleSymbol(reference) is not IAssemblySymbol assembly)
            continue;
          FindTypes(
            assembly.GlobalNamespace,
            descriptorInterface,
            buildingBlockInterface,
            filesystemDriverAdapterInterface,
            descriptors,
            buildingBlocks,
            filesystemDrivers,
            ct);
        }

        FindTypes(
          compilation.Assembly.GlobalNamespace,
          descriptorInterface,
          buildingBlockInterface,
          filesystemDriverAdapterInterface,
          descriptors,
          buildingBlocks,
          filesystemDrivers,
          ct);
      }

      descriptors.Sort((a, b) => StringComparer.Ordinal.Compare(a.FullName, b.FullName));
      buildingBlocks.Sort(StringComparer.Ordinal);
      filesystemDrivers.Sort(StringComparer.Ordinal);
      return (Descriptors: descriptors, BuildingBlocks: buildingBlocks, FilesystemDrivers: filesystemDrivers);
    });

    context.RegisterSourceOutput(allTypes, static (spc, types) => {
      EmitFormatRegistration(spc, types.Descriptors, types.BuildingBlocks, types.FilesystemDrivers);
      EmitFormatEnum(spc, types.Descriptors);
    });
  }

  private static void EmitFormatRegistration(
      SourceProductionContext spc,
      List<(string FullName, string Id, bool IsFilesystem)> descriptors,
      List<string> buildingBlocks,
      List<string> filesystemDrivers) {
    var sb = new StringBuilder();
    sb.AppendLine("// <auto-generated/>");
    sb.AppendLine("using Compression.Registry;");
    sb.AppendLine();
    sb.AppendLine("namespace Compression.Lib;");
    sb.AppendLine();
    sb.AppendLine("public static partial class FormatRegistration {");
    sb.AppendLine("  static partial void RegisterFormats() {");
    foreach (var (fullName, _, isFilesystem) in descriptors) {
      sb.AppendLine(isFilesystem
        ? $"    FormatRegistry.Register(new {fullName}(), isFilesystem: true);"
        : $"    FormatRegistry.Register(new {fullName}());");
    }
    sb.AppendLine("  }");
    sb.AppendLine();
    sb.AppendLine("  static partial void RegisterBuildingBlocks() {");
    foreach (var fullName in buildingBlocks)
      sb.AppendLine($"    BuildingBlockRegistry.Register(new {fullName}());");
    sb.AppendLine("  }");
    sb.AppendLine();
    sb.AppendLine("  static partial void RegisterFilesystemDrivers() {");
    foreach (var fullName in filesystemDrivers)
      sb.AppendLine($"    FormatRegistry.RegisterFilesystemDriver(new {fullName}());");
    sb.AppendLine("  }");
    sb.AppendLine("}");

    spc.AddSource("FormatRegistration.g.cs", sb.ToString());
  }

  private static void EmitFormatEnum(
      SourceProductionContext spc,
      List<(string FullName, string Id, bool IsFilesystem)> types) {
    var sb = new StringBuilder();
    sb.AppendLine("// <auto-generated/>");
    sb.AppendLine();
    sb.AppendLine("namespace Compression.Lib;");
    sb.AppendLine();
    sb.AppendLine("public static partial class FormatDetector {");
    sb.AppendLine("  public enum Format {");

    foreach (var special in SpecialFormats)
      sb.AppendLine($"    {special},");

    var specialSet = new HashSet<string>(SpecialFormats);
    foreach (var (_, id, _) in types)
      if (!specialSet.Contains(id))
        sb.AppendLine($"    {id},");

    sb.AppendLine("  }");
    sb.AppendLine("}");

    spc.AddSource("FormatDetector.Format.g.cs", sb.ToString());
  }

  private static void FindTypes(
      INamespaceSymbol ns,
      INamedTypeSymbol? descriptorInterface,
      INamedTypeSymbol? buildingBlockInterface,
      INamedTypeSymbol? filesystemDriverAdapterInterface,
      List<(string FullName, string Id, bool IsFilesystem)> descriptors,
      List<string> buildingBlocks,
      List<string> filesystemDrivers,
      System.Threading.CancellationToken ct) {
    foreach (var member in ns.GetMembers()) {
      ct.ThrowIfCancellationRequested();
      if (member is INamespaceSymbol childNs) {
        FindTypes(
          childNs,
          descriptorInterface,
          buildingBlockInterface,
          filesystemDriverAdapterInterface,
          descriptors,
          buildingBlocks,
          filesystemDrivers,
          ct);
      } else if (member is INamedTypeSymbol type &&
                 type.TypeKind == TypeKind.Class &&
                 !type.IsAbstract &&
                 type.DeclaredAccessibility == Accessibility.Public &&
                 HasParameterlessConstructor(type)) {
        var fullName = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

        if (descriptorInterface != null && Implements(type, descriptorInterface)) {
          var id = DeriveId(type.Name, "FormatDescriptor");
          var nsName = type.ContainingNamespace?.ToDisplayString() ?? string.Empty;
          var isFilesystem = nsName.Equals("FileSystem", StringComparison.Ordinal) ||
                             nsName.StartsWith("FileSystem.", StringComparison.Ordinal);
          descriptors.Add((fullName, id, isFilesystem));
        }

        if (buildingBlockInterface != null && Implements(type, buildingBlockInterface))
          buildingBlocks.Add(fullName);

        if (filesystemDriverAdapterInterface != null && Implements(type, filesystemDriverAdapterInterface))
          filesystemDrivers.Add(fullName);
      }
    }
  }

  private static string DeriveId(string className, string suffix) {
    if (className.EndsWith(suffix, StringComparison.Ordinal))
      return className.Substring(0, className.Length - suffix.Length);
    return className;
  }

  private static bool HasParameterlessConstructor(INamedTypeSymbol type) {
    foreach (var ctor in type.Constructors) {
      if (!ctor.IsStatic &&
          ctor.DeclaredAccessibility == Accessibility.Public &&
          ctor.Parameters.Length == 0)
        return true;
    }
    return false;
  }

  private static bool Implements(INamedTypeSymbol type, INamedTypeSymbol iface) {
    foreach (var i in type.AllInterfaces)
      if (SymbolEqualityComparer.Default.Equals(i, iface))
        return true;
    return false;
  }
}
