using System.IO;
using Codec.Mp3;

namespace Compression.Tests.Codecs.Mp3;

/// <summary>
/// Layer III decode checked against libavcodec's output for the same stream, not
/// against our own encoder.
/// </summary>
/// <remarks>
/// Four faults sat here, and none of them could be seen from a round trip: the
/// encoder made the same assumptions the decoder did, so the pair agreed with
/// itself and disagreed with everyone else.
///
/// The scalefactor-band tables are keyed on a combined version+rate index in which
/// MPEG-2.5 occupies the low rows and MPEG-1 the high ones. That index was built
/// the other way round, so every MPEG-1 stream — which is to say nearly every mp3 —
/// partitioned its spectrum with MPEG-2's band widths. The count1 region's
/// end-of-granule test then read the bit position 32 bits behind where it was,
/// letting the Huffman loop run past the granule and into the next one's data.
/// Short blocks were reordered with the source advancing two band widths per band
/// instead of three, so the three interleaved windows came out shuffled. And the
/// LSF scalefactor-compress ladder took the partition group before the one it
/// selected, which mattered whenever scalefac_compress ran past the first divisor
/// block.
///
/// Compounded, a joint-stereo LAME file decoded as full-scale noise: an rms of
/// 25 896 of error on a signal whose own rms is 1 846. Corrected, both streams
/// below land within one count of libavcodec everywhere.
/// </remarks>
[TestFixture]
public sealed class Mp3ForeignStreamTests {

  private static short[] Decode(string base64Stream) {
    using var input = new MemoryStream(Convert.FromBase64String(base64Stream), writable: false);
    using var output = new MemoryStream();
    Mp3Codec.Decompress(input, output);
    var bytes = output.ToArray();
    var pcm = new short[bytes.Length / 2];
    for (var i = 0; i < pcm.Length; ++i)
      pcm[i] = (short)(bytes[2 * i] | (bytes[2 * i + 1] << 8));
    return pcm;
  }

  private static short[] Reference(string base64Pcm) {
    var bytes = Convert.FromBase64String(base64Pcm);
    var pcm = new short[bytes.Length / 2];
    for (var i = 0; i < pcm.Length; ++i)
      pcm[i] = (short)(bytes[2 * i] | (bytes[2 * i + 1] << 8));
    return pcm;
  }

  /// <summary>
  /// Both decoders round a float spectrum into 16-bit, so disagreements of a count
  /// are expected and a sample sitting on a rounding boundary can differ by two.
  /// The rms bound is what carries the test: the faults this guards drove it to
  /// thousands, and it measures 0.11 and 0.14 on these two streams.
  /// </summary>
  private static void AssertMatchesLibavcodec(short[] ours, short[] reference) {
    Assert.That(ours, Has.Length.EqualTo(reference.Length), "decoded sample count");

    var worst = 0;
    var squaredError = 0.0;
    var squaredSignal = 0.0;
    for (var i = 0; i < reference.Length; ++i) {
      var error = ours[i] - reference[i];
      worst = Math.Max(worst, Math.Abs(error));
      squaredError += (double)error * error;
      squaredSignal += (double)reference[i] * reference[i];
    }

    var errorRms = Math.Sqrt(squaredError / reference.Length);
    Assert.Multiple(() => {
      Assert.That(worst, Is.LessThanOrEqualTo(2),
        "no sample may differ from libavcodec by more than rounding");
      Assert.That(errorRms, Is.LessThan(1.0),
        $"rms error {errorRms:F2} against a signal rms of {Math.Sqrt(squaredSignal / reference.Length):F0}");
    });
  }

