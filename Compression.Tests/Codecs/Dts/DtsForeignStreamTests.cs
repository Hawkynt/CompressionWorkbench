  private static short[] Decode(byte[] stream) {
    using var src = new MemoryStream(stream, writable: false);
    using var dst = new MemoryStream();
    DtsCodec.Decompress(src, dst);
    return ToSamples(dst.ToArray());
  }

  private static short[] Reference(string deflated) {
    using var src = new MemoryStream(Convert.FromBase64String(deflated), writable: false);
    using var inflate = new ZLibStream(src, CompressionMode.Decompress);
    using var dst = new MemoryStream();
    inflate.CopyTo(dst);
    return ToSamples(dst.ToArray());
  }

  private static short[] ToSamples(byte[] pcm) {
    var samples = new short[pcm.Length / 2];
    Buffer.BlockCopy(pcm, 0, samples, 0, samples.Length * 2);
    return samples;
  }

  private static void AssertMatchesReference(string streamBase64, string referenceBase64, int channels) {
    var reference = Reference(referenceBase64);
    var ours = Decode(Convert.FromBase64String(streamBase64));

    Assert.That(ours, Has.Length.EqualTo(reference.Length),
      "the decode must cover the whole stream, not stop at the first frame it cannot parse");
    Assert.That(reference.Length % channels, Is.Zero);

    var peak = 0;
    var exact = 0;
    for (var i = 0; i < reference.Length; ++i) {
      var d = Math.Abs(reference[i] - ours[i]);
      if (d > peak) peak = d;
      if (d == 0) ++exact;
    }

    Assert.Multiple(() => {
      Assert.That(peak, Is.LessThanOrEqualTo(1), "no sample may differ by more than one LSB");
      Assert.That((double)exact / reference.Length, Is.GreaterThan(0.98),
        "at least 98 % of samples must be identical, not merely close");
    });
  }

  /// <summary>0.064 s of pink noise, 48 kHz stereo at 384 kbit/s.</summary>
  [Test]
  [Category("RoundTrip")]
  public void StereoMatchesLibavcodec()
    => AssertMatchesReference(StereoPinkStream, StereoPinkReference, channels: 2);

  /// <summary>
  /// 0.08 s of a 997 Hz tone, 48 kHz mono at the full 1411 kbit/s. A single tone at that rate is
  /// coded with the finest quantizer steps in the table, the ones whose short-decimal spelling was
  /// 0.14 percent off; broadband content never reaches them.
  /// </summary>
  [Test]
  [Category("RoundTrip")]
  public void FineQuantizedToneMatchesLibavcodec()
    => AssertMatchesReference(ToneStream, ToneReference, channels: 1);

  /// <summary>
  /// 0.05 s of six distinct tones, 48 kHz 5.1 at 768 kbit/s. The core transmits the front channels
  /// centre-first and the LFE last, so this covers both the channel map and the LFE interpolation
  /// filter, whose history has to survive the frame boundary.
  /// </summary>
  [Test]
  [Category("RoundTrip")]
  public void SurroundMatchesLibavcodec()
    => AssertMatchesReference(SurroundStream, SurroundReference, channels: 6);

  /// <summary>Stream info has to agree with libavcodec's view of the same stream.</summary>
  [Test]
  [Category("HappyPath")]
  public void SurroundStreamInfoMatchesLibavcodec() {
    using var src = new MemoryStream(Convert.FromBase64String(SurroundStream), writable: false);
    var info = DtsCodec.ReadStreamInfo(src);

    Assert.Multiple(() => {
      Assert.That(info.SampleRate, Is.EqualTo(48_000));
      Assert.That(info.Channels, Is.EqualTo(6));
      Assert.That(info.Amode, Is.EqualTo(9));
      Assert.That(info.Lfe, Is.True);
    });
