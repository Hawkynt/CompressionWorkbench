  [TestCase("v1")]
  [TestCase("v2")]
  public void DecodeMatchesReferenceDecoderSampleBySample(string version) {
    var (asfBase64, pcmBase64) = version == "v1" ? (WmaV1Asf, FfmpegPcmV1) : (WmaV2Asf, FfmpegPcmV2);
    var expected = ToSamples(Convert.FromBase64String(pcmBase64));
    var actual = DecodeMono(Convert.FromBase64String(asfBase64));

    Assert.That(actual.Length, Is.GreaterThanOrEqualTo(ReferenceDelay + expected.Length),
      "decoder produced too few samples to cover the reference output.");

    long sumSq = 0;
    var peak = 0;
    var identical = 0;
    for (var i = 0; i < expected.Length; ++i) {
      var d = actual[ReferenceDelay + i] - expected[i];
      sumSq += (long)d * d;
      if (Math.Abs(d) > peak) peak = Math.Abs(d);
      if (d == 0) ++identical;
    }
    var rmse = Math.Sqrt((double)sumSq / expected.Length);
    var identicalPercent = 100.0 * identical / expected.Length;

    Assert.Multiple(() => {
      Assert.That(peak, Is.LessThanOrEqualTo(1), "peak sample error against the reference decode");
      Assert.That(rmse, Is.LessThan(0.25), "rms sample error against the reference decode");
      Assert.That(identicalPercent, Is.GreaterThan(99.0), "share of bit-identical samples");
    });
  }

  private static short[] ToSamples(byte[] pcm) {
    var samples = new short[pcm.Length / 2];
    Buffer.BlockCopy(pcm, 0, samples, 0, samples.Length * 2);
    return samples;
  }

  /// <summary>Decodes the single mono WMA stream in an ASF container to 16-bit samples.</summary>
  private static short[] DecodeMono(byte[] asf) {
    var descriptor = new AsfFormatDescriptor();
    using var input = new MemoryStream(asf);
    var channels = descriptor.List(input, null).Where(e => e.Kind == "Channel").ToList();
    Assert.That(channels, Has.Count.EqualTo(1), "expected exactly one decoded channel WAV");

    input.Position = 0;
    using var wav = new MemoryStream();
    descriptor.ExtractEntry(input, channels[0].Name, wav, null);
    return ToSamples(WavData(wav.ToArray()));
  }

  /// <summary>Returns the payload of a canonical PCM WAV's <c>data</c> chunk.</summary>
  private static byte[] WavData(byte[] wav) {
    var pos = 12; // past "RIFF" <size> "WAVE"
    while (pos + 8 <= wav.Length) {
      var id = System.Text.Encoding.ASCII.GetString(wav, pos, 4);
      var size = BitConverter.ToInt32(wav, pos + 4);
      pos += 8;
      if (id == "data")
        return wav[pos..(pos + size)];
      pos += size + (size & 1);
    }
    throw new InvalidDataException("no data chunk");
  }
