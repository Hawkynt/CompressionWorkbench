/// <summary>
/// WMA v1/v2 decode checked against libavcodec's own decode of the same file.
/// </summary>
/// <remarks>
/// The inverse MDCT evaluated its cosine kernel at twice the phase step the transform
/// is defined with — <c>pi/(2n)</c> instead of <c>pi/(4n)</c> — and carried the opposite
