using Hawkynt.Algorithms.Hashing;
using NUnit.Framework;

namespace Compression.Tests.Hashing;

[TestFixture]
public sealed class StreebogTests {
  private const string RfcMessage1 =
    "3031323334353637383930313233343536373839303132333435363738393031" +
    "32333435363738393031323334353637383930313233343536373839303132";

  private const string RfcMessage2 =
    "D1E520E2E5F2F0E82C20D1F2F0E8E1EEE6E820E2EDF3F6E82C20E2E5FEF2FA20" +
    "F120ECEEF0FF20F1F2F0E5EBE0ECE820EDE020F5F0E0E1F0FBFF20EFEBFAEAFB20C8E3EEF0E5E2FB";

  [TestCase("", "3F539A213E97C802CC229D474C6AA32A825A360B2A933A949FD925208D9CE1BB")]
  [TestCase(RfcMessage1, "9D151EEFD8590B89DAA6BA6CB74AF9275DD051026BB149A452FD84E5E57B5500")]
  [TestCase(RfcMessage2, "9DD2FE4E90409E5DA87F53976D7405B0C0CAC628FC669A741D50063C557E8F50")]
  public void Streebog256MatchesRfc6986(string inputHex, string expected) =>
    Assert.That(Convert.ToHexString(Streebog256.Compute(Convert.FromHexString(inputHex))), Is.EqualTo(expected));

  [TestCase("", "8E945DA209AA869F0455928529BCAE4679E9873AB707B55315F56CEB98BEF0A7362F715528356EE83CDA5F2AAC4C6AD2BA3A715C1BCD81CB8E9F90BF4C1C1A8A")]
  [TestCase(RfcMessage1, "1B54D01A4AF5B9D5CC3D86D68D285462B19ABC2475222F35C085122BE4BA1FFA00AD30F8767B3A82384C6574F024C311E2A481332B08EF7F41797891C1646F48")]
  [TestCase(RfcMessage2, "1E88E62226BFCA6F9994F1F2D51569E0DAF8475A3B0FE61A5300EEE46D961376035FE83549ADA2B8620FCD7C496CE5B33F0CB9DDDC2B6460143B03DABAC9FB28")]
  public void Streebog512MatchesRfc6986(string inputHex, string expected) =>
    Assert.That(Convert.ToHexString(Streebog512.Compute(Convert.FromHexString(inputHex))), Is.EqualTo(expected));
}