using Hawkynt.Algorithms.Hashing;
using NUnit.Framework;

namespace Compression.Tests.Hashing;

[TestFixture]
public sealed class FugueTests {
  [TestCase(224, "", "E2CD30D51A913C4ED2388A141F90CAA4914DE43010849E7B8A7A9CCD")]
  [TestCase(224, "CC", "34602EA95B2B9936B9A04BA14B5DC463988DF90B1A46F90DD716B60F")]
  [TestCase(256, "", "D6EC528980C130AAD1D1ACD28B9DD8DBDEAE0D79EDED1FCA72C2AF9F37C2246F")]
  [TestCase(256, "CC", "B894EB2DF58162F6C48D495F156E73BD086DD13DB407EE38781177BB23D129BB")]
  [TestCase(384, "", "466D05F6812B58B8628E53816B2A99D173B804A964DE971829159C3791AC8B524EEBBF5FC73BA40EA8EEA446D5424A30")]
  [TestCase(384, "CC", "436868CD6804B803DAC432ED561BB40F91F624A10F2A368702359841CFDA6909115628CA4977B3F8063A3B87FC7A0984")]
  [TestCase(512, "", "3124F0CBB5A1C2FB3CE747ADA63ED2AB3BCD74795CEF2B0E805D5319FCC360B4617B6A7EB631D66F6D106ED0724B56FA8C1110F9B8DF1C6898E7CA3C2DFCCF79")]
  [TestCase(512, "CC", "2EF4115479B060FC64A4D6F6913A39E326AFC81DEB4E39D71C573DF5ED132200E7C784BAB1804930CAD16847F16CBDA59A865BBD928EBC17D33689FEF233C10B")]
  public void MatchesSphlibVectors(int bits, string inputHex, string expectedHex) {
    var data = Convert.FromHexString(inputHex);
    Assert.That(Convert.ToHexString(Fugue.Compute(data, bits)), Is.EqualTo(expectedHex));
  }

  [Test]
  public void ExposesEnumerableSupportedSizes() {
    Assert.That(Fugue.SupportedHashSizes.EnumerateSizes(), Is.EqualTo(new[] { 224, 256, 384, 512 }));
    Assert.Throws<ArgumentOutOfRangeException>(() => Fugue.Compute([], 320));
  }
}
