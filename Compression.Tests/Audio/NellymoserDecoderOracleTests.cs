  [Test]
  [Category("RoundTrip")]
  public void DecodeTracksLibavcodecWithinRounding() {
    var decoded = NellymoserCodec.Decode(Convert.FromBase64String(EncodedBlocks), 11_025);

    Assert.That(decoded, Has.Length.EqualTo(FfmpegPcm.Length));

    long sumSquares = 0;
    var worst = 0;
    for (var i = 0; i < decoded.Length; ++i) {
      var delta = decoded[i] - FfmpegPcm[i];
      sumSquares += (long)delta * delta;
      worst = Math.Max(worst, Math.Abs(delta));
    }

    var rms = Math.Sqrt((double)sumSquares / decoded.Length);
    Assert.Multiple(() => {
      Assert.That(rms, Is.LessThan(4.0), "rms difference from libavcodec");
      Assert.That(worst, Is.LessThan(64), "worst single-sample difference from libavcodec");
    });
  }

  /// <summary>
  /// The polarity, on its own. An inverted decode still correlates with the
