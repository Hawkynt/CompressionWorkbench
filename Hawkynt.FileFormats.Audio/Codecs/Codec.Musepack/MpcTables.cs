  private static sbyte[] BuildIdx5(int which) {
    // FFmpeg lists these out by hand; they are the three coordinates of a
    // base-5 odometer over {-2,-1,0,1,2}. idx50 cycles fastest, idx52 slowest.
    var result = new sbyte[125];
    for (var i = 0; i < 125; ++i) {
      var digit = which switch {
        0 => i % 5,
        1 => (i / 5) % 5,
        _ => (i / 25) % 5,
      };
      result[i] = (sbyte)(digit - 2);
    }
    return result;
  }

