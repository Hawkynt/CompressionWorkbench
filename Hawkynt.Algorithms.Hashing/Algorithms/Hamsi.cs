  public static byte[] Compute(ReadOnlySpan<byte> data, int hashSizeBits = 512) {
    if (!SupportedHashSizes.Supports(hashSizeBits))
      throw new ArgumentOutOfRangeException(nameof(hashSizeBits));

    var h = (uint[])(hashSizeBits == 384 ? Iv384.Clone() : Iv512.Clone());
    var offset = 0;
    while (offset + 8 <= data.Length) {
      Compress(h, data.Slice(offset, 8), 6, AlphaNormal);
      offset += 8;
    }

    Span<byte> finalBlock = stackalloc byte[8];
    finalBlock.Clear();
    data[offset..].CopyTo(finalBlock);
    finalBlock[data.Length - offset] = 0x80;
    Compress(h, finalBlock, 6, AlphaNormal);

    Span<byte> countBlock = stackalloc byte[8];
