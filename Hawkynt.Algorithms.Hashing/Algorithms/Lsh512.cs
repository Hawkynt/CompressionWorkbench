  public static byte[] Compute(ReadOnlySpan<byte> data, ulong[] initial, int outputBytes) {
    var left = initial[..8].ToArray();
    var right = initial[8..].ToArray();
    var offset = 0;
    while (offset + 256 <= data.Length) {
      Compress(left, right, data.Slice(offset, 256));
      offset += 256;
    }

    var final = new byte[256];
    data[offset..].CopyTo(final);
    final[data.Length - offset] = 0x80;
    Compress(left, right, final);

    for (var i = 0; i < 8; ++i)
      left[i] ^= right[i];
    var result = new byte[outputBytes];
    for (var i = 0; i < outputBytes / 8; ++i)
      BinaryPrimitives.WriteUInt64LittleEndian(result.AsSpan(i * 8, 8), left[i]);
    return result;
  }

  private static void Compress(ulong[] left, ulong[] right, ReadOnlySpan<byte> block) {
    var sub = new ulong[32];
    for (var i = 0; i < 8; ++i) {
      sub[i] = BinaryPrimitives.ReadUInt64LittleEndian(block.Slice(i * 8, 8));
      sub[8+i] = BinaryPrimitives.ReadUInt64LittleEndian(block.Slice(64 + i * 8, 8));
      sub[16+i] = BinaryPrimitives.ReadUInt64LittleEndian(block.Slice(128 + i * 8, 8));
      sub[24+i] = BinaryPrimitives.ReadUInt64LittleEndian(block.Slice(192 + i * 8, 8));
    }

    Add(left,right,sub,0); Mix(left,right,23,59,0); Permute(left,right);
    Add(left,right,sub,16); Mix(left,right,7,3,8); Permute(left,right);
    for (var step=1;step<14;++step) {
      ExpandEven(sub); Add(left,right,sub,0); Mix(left,right,23,59,step*16); Permute(left,right);
      ExpandOdd(sub); Add(left,right,sub,16); Mix(left,right,7,3,step*16+8); Permute(left,right);
    }
    ExpandEven(sub); Add(left,right,sub,0);
  }

  private static void Add(ulong[] left, ulong[] right, ulong[] sub, int offset) {
    for (var i=0;i<8;++i) { left[i]^=sub[offset+i]; right[i]^=sub[offset+8+i]; }
  }

  private static void Mix(ulong[] left, ulong[] right, int alpha, int beta, int constants) {
    for (var i=0;i<8;++i) {
      left[i] = BitOperations.RotateLeft(unchecked(left[i] + right[i]), alpha) ^ StepConstants[constants+i];
      right[i] = BitOperations.RotateLeft(unchecked(right[i] + left[i]), beta);
      left[i] = unchecked(left[i] + right[i]);
      if (i > 0)
        right[i] = BitOperations.RotateLeft(right[i], Gamma[i]);
    }
  }

  private static void ExpandEven(ulong[] s) { ExpandQuarter(s,0,16); ExpandQuarter(s,8,24); }
  private static void ExpandOdd(ulong[] s) { ExpandQuarter(s,16,0); ExpandQuarter(s,24,8); }

  private static void ExpandQuarter(ulong[] s, int target, int other) {
    var a0=s[target]; var a1=s[target+1]; var a2=s[target+2]; var a3=s[target+3];
    var a4=s[target+4]; var a5=s[target+5]; var a6=s[target+6]; var a7=s[target+7];
    s[target]=unchecked(s[other]+a3); s[target+3]=unchecked(s[other+3]+a1);
    s[target+1]=unchecked(s[other+1]+a2); s[target+2]=unchecked(s[other+2]+a0);
    s[target+4]=unchecked(s[other+4]+a7); s[target+7]=unchecked(s[other+7]+a6);
    s[target+6]=unchecked(s[other+6]+a5); s[target+5]=unchecked(s[other+5]+a4);
  }

  private static void Permute(ulong[] l, ulong[] r) {
    var t=l[0];
    l[0]=l[6]; l[6]=r[6]; r[6]=r[2]; r[2]=l[1];
    l[1]=l[4]; l[4]=r[4]; r[4]=r[0]; r[0]=l[2];
    l[2]=l[5]; l[5]=r[7]; r[7]=r[1]; r[1]=t;
    t=l[3]; l[3]=l[7]; l[7]=r[5]; r[5]=r[3]; r[3]=t;
  }
