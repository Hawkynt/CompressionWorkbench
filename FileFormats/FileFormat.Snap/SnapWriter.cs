using System.Globalization;
using System.Text;
using Compression.Registry;
using FileSystem.SquashFs;

namespace FileFormat.Snap;

/// <summary>
/// WORM writer that produces a Snap package by wrapping a fresh SquashFS v4
/// image holding the application payload. Every input becomes a file in the
/// SquashFS at its archive name. When the inputs do not already include
/// <c>meta/snap.yaml</c>, a minimal manifest is synthesised so the resulting
/// archive is structurally a Snap and not just a generic SquashFS.
/// </summary>
public static class SnapWriter {

  /// <summary>Default snap name used when no manifest is provided.</summary>
  public const string DefaultName = "untitled";

  /// <summary>Default snap version used when no manifest is provided.</summary>
  public const string DefaultVersion = "0.1";

  /// <summary>Default summary used when no manifest is provided.</summary>
  public const string DefaultSummary = "Generated by CompressionWorkbench";

  /// <summary>
  /// Writes a Snap-shaped SquashFS image to <paramref name="output"/>.
  /// </summary>
  /// <param name="output">Destination stream. The image is finalised before return.</param>
  /// <param name="inputs">Files and directories to embed inside the SquashFS image.</param>
  /// <param name="options">Optional creation tunables — currently consulted for
  /// <c>snap_name</c>, <c>snap_version</c>, <c>snap_summary</c> and <c>snap_base</c>
  /// when a manifest must be synthesised.</param>
  public static void Write(
      Stream output,
      IReadOnlyList<ArchiveInputInfo> inputs,
      FormatCreateOptions options) {
    ArgumentNullException.ThrowIfNull(output);
    ArgumentNullException.ThrowIfNull(inputs);

    var hasManifest = false;
    var directories = new List<string>();
    var files = new List<(string Name, byte[] Data)>();
    foreach (var i in inputs) {
      var name = NormalizePath(i.ArchiveName);
      if (i.IsDirectory) {
        directories.Add(name);
        continue;
      }
      var data = i.ReadContent();
      files.Add((name, data));
      if (string.Equals(name, "meta/snap.yaml", StringComparison.Ordinal))
        hasManifest = true;
    }

    using var w = new SquashFsWriter(output, leaveOpen: true);
    foreach (var d in directories)
      w.AddDirectory(d);
    foreach (var (name, data) in files)
      w.AddFile(name, data);

    if (!hasManifest) {
      var manifest = BuildDefaultManifest(options);
      w.AddFile("meta/snap.yaml", Encoding.UTF8.GetBytes(manifest));
    }
  }

  private static string BuildDefaultManifest(FormatCreateOptions options) {
    var name = options?.GetOption("snap_name", DefaultName) ?? DefaultName;
    var version = options?.GetOption("snap_version", DefaultVersion) ?? DefaultVersion;
    var summary = options?.GetOption("snap_summary", DefaultSummary) ?? DefaultSummary;
    var baseSnap = options?.GetOption("snap_base", "core22") ?? "core22";

    var sb = new StringBuilder();
    sb.Append(CultureInfo.InvariantCulture, $"name: {EscapeYaml(name)}\n");
    sb.Append(CultureInfo.InvariantCulture, $"version: {EscapeYaml(version)}\n");
    sb.Append(CultureInfo.InvariantCulture, $"summary: {EscapeYaml(summary)}\n");
    sb.Append("description: |\n  Synthesised by CompressionWorkbench WORM writer.\n");
    sb.Append("confinement: strict\n");
    sb.Append("grade: stable\n");
    sb.Append(CultureInfo.InvariantCulture, $"base: {EscapeYaml(baseSnap)}\n");
    return sb.ToString();
  }

  private static string EscapeYaml(string value) {
    if (string.IsNullOrEmpty(value)) return "''";
    var needsQuote = false;
    foreach (var c in value) {
      if (c == ':' || c == '#' || c == '\n' || c == '\r' || c == '"' || c == '\'') {
        needsQuote = true;
        break;
      }
    }
    if (!needsQuote) return value;
    return "'" + value.Replace("'", "''") + "'";
  }

  private static string NormalizePath(string p) => p.Replace('\\', '/').Trim('/');
}
